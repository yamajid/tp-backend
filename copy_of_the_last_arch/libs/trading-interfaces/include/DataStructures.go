package main

// ConnectionStatus represents the connection state
type ConnectionStatus int

const (
	DISCONNECTED ConnectionStatus = iota
	CONNECTING
	CONNECTED
	AUTHENTICATED
	FAILED
)

func (cs ConnectionStatus) String() string {
	switch cs {
	case DISCONNECTED:
		return "DISCONNECTED"
	case CONNECTING:
		return "CONNECTING"
	case CONNECTED:
		return "CONNECTED"
	case AUTHENTICATED:
		return "AUTHENTICATED"
	case FAILED:
		return "FAILED"
	default:
		return "UNKNOWN"
	}
}

